.section .text
bsod:
    mov r1, #0x00020000 ; framebuffer address
    mov r2, #0 ; counter
    mov r3, #0xD087D087 ; colour
    mov r5, #0x153600
loop:
    add r4, r1, r2
    str r3, [r4]
    add r2, r2, #4
    cmp r2, r5
    jne $loop

    mov r0, $msg_bsod
    mov r1, #0
    mov r2, #0
    mov r3, #0xFFFF
    call $draw_string
    mov r0, $msg_bsod2
    mov r1, #0
    mov r2, #20
    mov r3, #0xFFFF
    call $draw_string
    halt

.section .data
